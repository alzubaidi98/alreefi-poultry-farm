export function getAgeThresholdForDay(cycleDay, ageThresholds = DEFAULT_AGE_THRESHOLDS) {
  const day = Math.max(1, Number(cycleDay) || 1);
  return (
    ageThresholds.find((band) => day >= band.minDay && day <= band.maxDay) ||
    ageThresholds[ageThresholds.length - 1]
  );
}

export function calculateHouseInventory(house, chicksPerCarton = 100, logs = []) {
  const initialChicks = Math.max(0, Number(house.cartons || 0) * Number(chicksPerCarton || 100));
  const houseLogs = logs.filter((l) => l.houseId === house.id && l.cycleNumber === house.cycleNumber);
  const loggedMortalities = houseLogs.reduce((sum, l) => sum + Number(l.mortalities || 0), 0);
  const loggedCulls = houseLogs.reduce((sum, l) => sum + Number(l.culls || 0), 0);

  const totalMortalities = Number(house.historicalMortalities || 0) + loggedMortalities;
  const totalCulls = Number(house.historicalCulls || 0) + loggedCulls;
  const calculatedActive = Math.max(0, initialChicks - totalMortalities - totalCulls);

  const isOverridden =
    house.manualCountOverride !== null &&
    house.manualCountOverride !== undefined &&
    house.manualCountOverride !== '';

  const activeChicks = isOverridden ? Math.max(0, Number(house.manualCountOverride)) : calculatedActive;
  const mortalityPct = initialChicks > 0 ? Number((((totalMortalities + totalCulls) / initialChicks) * 100).toFixed(2)) : 0;

  return {
    initialChicks,
    totalMortalities,
    totalCulls,
    calculatedActive,
    activeChicks,
    isOverridden,
    mortalityPct,
  };
}

export function evaluateHouseEnvironmentStatus(house, settings) {
  if (house.isActive === false) {
    return {
      status: 'INACTIVE',
      reasons: ['House is marked Inactive / Offline'],
      targetBand: null,
    };
  }

  if (house.phase === 'cleaning') {
    return {
      status: 'CLEANING',
      reasons: [`Cleaning Phase: Day ${house.cleaningDay} of ${house.targetCleaningDays || 14}`],
      targetBand: null,
    };
  }

  const threshold = getAgeThresholdForDay(house.cycleDay, settings?.ageThresholds || DEFAULT_AGE_THRESHOLDS);
  const humidityMin = settings?.environmentLimits?.humidityMin ?? 50;
  const humidityMax = settings?.environmentLimits?.humidityMax ?? 65;
  const nh3Warn = settings?.environmentLimits?.ammoniaWarningPpm ?? 15;
  const nh3Alert = settings?.environmentLimits?.ammoniaAlertPpm ?? 20;
  const co2Warn = settings?.environmentLimits?.co2WarningPpm ?? 2500;
  const co2Alert = settings?.environmentLimits?.co2AlertPpm ?? 3000;
  const negMin = settings?.environmentLimits?.negPressureMinPa ?? 18;
  const negMax = settings?.environmentLimits?.negPressureMaxPa ?? 38;

  const zoneTemps = [
    { name: 'Start Zone', val: Number(house.zones?.start ?? 0) },
    { name: 'Middle Zone', val: Number(house.zones?.middle ?? 0) },
    { name: 'End Zone', val: Number(house.zones?.end ?? 0) },
  ];

  let status = 'OPTIMAL';
  const reasons = [];

  for (const z of zoneTemps) {
    const highDiff = z.val - threshold.targetMaxC;
    const lowDiff = threshold.targetMinC - z.val;
    const maxDeviation = Math.max(highDiff, lowDiff, 0);

    if (maxDeviation >= threshold.alertOffsetC) {
      status = 'ALERT';
      reasons.push(`${z.name} (${z.val.toFixed(1)}°C) out of ${threshold.label} range`);
    } else if (maxDeviation > 0) {
      if (status !== 'ALERT') status = 'ATTENTION';
      reasons.push(`${z.name} (${z.val.toFixed(1)}°C) drifting from ${threshold.targetMinC}–${threshold.targetMaxC}°C`);
    }
  }

  const nh3 = Number(house.zones?.ammoniaPpm ?? 0);
  if (nh3 >= nh3Alert) {
    status = 'ALERT';
    reasons.push(`Ammonia critical at ${nh3} ppm (limit < ${nh3Alert} ppm)`);
  } else if (nh3 >= nh3Warn) {
    if (status !== 'ALERT') status = 'ATTENTION';
    reasons.push(`Ammonia elevated at ${nh3} ppm`);
  }

  const co2 = Number(house.zones?.co2Ppm ?? house.co2Ppm ?? 1800);
  if (co2 >= co2Alert) {
    status = 'ALERT';
    reasons.push(`CO₂ critical at ${co2} ppm (limit < ${co2Alert} ppm)`);
  } else if (co2 >= co2Warn) {
    if (status !== 'ALERT') status = 'ATTENTION';
    reasons.push(`CO₂ elevated at ${co2} ppm (warn >= ${co2Warn} ppm)`);
  }

  const negPa = Number(house.zones?.negativePressurePa ?? house.negativePressurePa ?? 25);
  if (negPa <= negMin - 2 || negPa >= negMax + 4) {
    status = 'ALERT';
    reasons.push(`Negative pressure critical at ${negPa} Pa (target ${negMin}–${negMax} Pa)`);
  } else if (negPa < negMin || negPa > negMax) {
    if (status !== 'ALERT') status = 'ATTENTION';
    reasons.push(`Negative pressure drifting at ${negPa} Pa (target ${negMin}–${negMax} Pa)`);
  }

  const hum = Number(house.zones?.humidity ?? 55);
  if (hum < humidityMin - 10 || hum > humidityMax + 10) {
    if (status !== 'ALERT') status = 'ATTENTION';
    reasons.push(`Humidity ${hum}% outside ideal ${humidityMin}–${humidityMax}%`);
  }

  if (reasons.length === 0) {
    reasons.push(
      `All 3 interior zones (${threshold.targetMinC}–${threshold.targetMaxC}°C), CO₂ (<${co2Warn} ppm) & Pressure (${negMin}–${negMax} Pa) optimal`
    );
  }

  return { status, reasons, targetBand: threshold };
}

function buildDailyCycleSeries(
  cycleNum,
  baseOutside,
  avgMortality,
  weightSlope,
  fcrBase,
  offsets = { tempDelta: 0, co2Delta: 0, pressureDelta: 0, mortDelta: 0, weightDelta: 0, waterDelta: 0 }
) {
  const days = [];
  let cumulativeFeedTons = 0;
  for (let d = 1; d <= 35; d++) {
    const week = Math.ceil(d / 7);
    const targetTemp = Math.max(23.5, 32.5 - (d - 1) * 0.27);
    const outsideTemp = Number((baseOutside + Math.sin(d * 0.4) * 2.4).toFixed(1));
    const startTemp = Number((targetTemp + (d % 5 === 0 ? 1.0 : 0.2) + offsets.tempDelta).toFixed(1));
    const middleTemp = Number((targetTemp + (d % 4 === 0 ? 1.5 : 0.6) + offsets.tempDelta).toFixed(1));
    const endTemp = Number((targetTemp + (d % 6 === 0 ? 2.0 : 0.9) + offsets.tempDelta).toFixed(1));
    const humidity = Math.min(72, Math.max(46, Math.round(54 + d * 0.25 + Math.sin(d * 0.7) * 4)));
    const ammoniaPpm = Number(Math.max(3, 4 + d * 0.44 + (d > 25 ? 2.4 : 0) + offsets.tempDelta * 1.4).toFixed(1));
    const co2Ppm = Math.round(
      Math.max(950, 1250 + d * 52 + (d > 24 ? 220 : 0) + Math.sin(d * 0.6) * 110 + offsets.co2Delta)
    );
    const negativePressurePa = Number(
      Math.max(12, Math.min(38, 28 - d * 0.14 + Math.cos(d * 0.5) * 2.2 + offsets.pressureDelta)).toFixed(1)
    );
    const mortalities = Math.max(
      2,
      Math.round(avgMortality + offsets.mortDelta + (d <= 5 ? 4 : 0) + (d > 28 ? 5 : 0) + Math.sin(d) * 3)
    );
    const culls = Math.max(1, Math.round(mortalities * 0.4));
    const dailyFeedKg = Math.round(320 + d * 68 + (d > 21 ? 210 : 0));
    cumulativeFeedTons = Number((cumulativeFeedTons + dailyFeedKg / 1000).toFixed(2));
    const waterLiters = Math.round(dailyFeedKg * 1.95 + (d > 20 ? 320 : 0) + (offsets.waterDelta || 0));
    const waterGallons = Math.round(litersToGallons(waterLiters));
    const avgWeightGrams = Math.round(45 + d * weightSlope + Math.pow(d, 1.32) * 5.2 + offsets.weightDelta);

    days.push({
      day: d,
      label: `Day ${d}`,
      week: `Week ${week}`,
      startTemp,
      middleTemp,
      endTemp,
      outsideTemp,
      humidity,
      ammoniaPpm,
      co2Ppm,
      negativePressurePa,
      mortalities,
      culls,
      dailyFeedKg,
      cumulativeFeedTons,
      waterGallons,
      waterLiters,
      avgWeightGrams,
      fcr: Number((fcrBase + d * 0.014).toFixed(2)),
    });
  }
  return days;
}

