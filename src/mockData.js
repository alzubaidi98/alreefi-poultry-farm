function buildCycleWithHouseBreakdown(cycleNum, baseOutside, avgMortality, weightSlope, fcrBase) {
  const dailySeries = buildDailyCycleSeries(cycleNum, baseOutside, avgMortality, weightSlope, fcrBase);
  const byHouseSeries = {};
  for (const [houseId, offsets] of Object.entries(HOUSE_SERIES_OFFSETS)) {
    byHouseSeries[houseId] = buildDailyCycleSeries(cycleNum, baseOutside, avgMortality, weightSlope, fcrBase, offsets);
  }
  return { dailySeries, byHouseSeries, houseOffsets: HOUSE_SERIES_OFFSETS };
}

