export function gallonsToLiters(gal) {
  return Number((Number(gal || 0) * 3.78541).toFixed(2));
}

export function litersToGallons(liters) {
  return Number((Number(liters || 0) / 3.78541).toFixed(2));
}

/**
 * Generates sequential job number formatted as '<2-digit house>-<3-digit taskNumber>-<2-digit occurrence>'
 * e.g. '01-001-04'. Uses '00' for farm/role-wide tasks without a specific house code.
 */
export function generateNextJobNumber(tasks = [], houseCodeOrNum = '01', taskNumber = '001') {
  const houseDigits = String(houseCodeOrNum ?? '').replace(/\D/g, '');
  const house2 = (houseDigits || '00').padStart(2, '0').slice(-2);

  const taskDigits = String(taskNumber ?? '').replace(/\D/g, '');
  const task3 = (taskDigits || '001').padStart(3, '0').slice(-3);

  const prefix = `${house2}-${task3}-`;
  let maxOccurrence = 0;

  for (const t of tasks || []) {
    const jobNum = String(t?.jobNumber || '');
    if (jobNum.startsWith(prefix)) {
      const parts = jobNum.split('-');
      const occ = parseInt(parts[2], 10);
      if (!Number.isNaN(occ) && occ > maxOccurrence) {
        maxOccurrence = occ;
      }
    }
  }

  return `${prefix}${String(maxOccurrence + 1).padStart(2, '0')}`;
}

